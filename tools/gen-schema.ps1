W ""

# Index grouped alphabetically with row counts
foreach ($g in $tables) {
  $rc = if ($rcMap.ContainsKey($g.Name)) { $rcMap[$g.Name] } else { 0 }
  $tw = if ($temporalSet.ContainsKey($g.Name)) { ' *(temporal)*' } else { '' }
  W "- [``$($g.Name)``](#$($g.Name.ToLower())) -- $($g.Group.Count) cols, ~$rc rows$tw"
}
