$ErrorActionPreference = 'Stop'
$cs = "Server=(localdb)\MSSQLLocalDB;Database=Prose;Integrated Security=true;TrustServerCertificate=true"

function Query($sql) {
  $cn = New-Object System.Data.SqlClient.SqlConnection $cs
  $cn.Open()
  $cmd = $cn.CreateCommand()
  $cmd.CommandText = $sql
  $cmd.CommandTimeout = 120
  $da = New-Object System.Data.SqlClient.SqlDataAdapter $cmd
  $dt = New-Object System.Data.DataTable
  [void]$da.Fill($dt)
  $cn.Close()
  return ,$dt
}

$cols = Query @"
SELECT c.TABLE_NAME, c.ORDINAL_POSITION, c.COLUMN_NAME, c.DATA_TYPE,
       c.CHARACTER_MAXIMUM_LENGTH, c.NUMERIC_PRECISION, c.NUMERIC_SCALE, c.IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS c
JOIN INFORMATION_SCHEMA.TABLES t ON t.TABLE_NAME = c.TABLE_NAME AND t.TABLE_TYPE = 'BASE TABLE'
WHERE c.TABLE_NAME NOT LIKE '%[_]History'
ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION
"@

$pks = Query @"
SELECT tc.TABLE_NAME, ku.COLUMN_NAME
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE ku ON tc.CONSTRAINT_NAME = ku.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_TYPE = 'PRIMARY KEY'
"@

$fks = Query @"
SELECT cp.TABLE_NAME AS FromTable, kcu.COLUMN_NAME AS FromCol,
       rt.TABLE_NAME AS ToTable, rkcu.COLUMN_NAME AS ToCol
FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc
JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS cp ON rc.CONSTRAINT_NAME = cp.CONSTRAINT_NAME
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu ON kcu.CONSTRAINT_NAME = rc.CONSTRAINT_NAME
JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS rt ON rc.UNIQUE_CONSTRAINT_NAME = rt.CONSTRAINT_NAME
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE rkcu ON rkcu.CONSTRAINT_NAME = rt.CONSTRAINT_NAME AND rkcu.ORDINAL_POSITION = kcu.ORDINAL_POSITION
"@

# Temporal (system-versioned) base tables
$temporal = Query @"
SELECT t.name AS TableName
FROM sys.tables t
WHERE t.temporal_type = 2
"@

# Row counts for base tables
$rowcounts = Query @"
SELECT t.name AS TableName, SUM(p.rows) AS Rows
FROM sys.tables t
JOIN sys.partitions p ON p.object_id = t.object_id AND p.index_id IN (0,1)
WHERE t.name NOT LIKE '%[_]History'
GROUP BY t.name
"@

# Build lookups
$pkSet = @{}
foreach ($r in $pks.Rows) { $pkSet["$($r.TABLE_NAME)|$($r.COLUMN_NAME)"] = $true }

$fkMap = @{}
foreach ($r in $fks.Rows) { $fkMap["$($r.FromTable)|$($r.FromCol)"] = "$($r.ToTable).$($r.ToCol)" }

$temporalSet = @{}
foreach ($r in $temporal.Rows) { $temporalSet["$($r.TableName)"] = $true }

$rcMap = @{}
foreach ($r in $rowcounts.Rows) { $rcMap["$($r.TableName)"] = [long]$r.Rows }

# Group columns by table
$tables = $cols.Rows | Group-Object TABLE_NAME | Sort-Object Name

$sb = New-Object System.Text.StringBuilder
function W($s) { [void]$sb.AppendLine($s) }

$today = Get-Date -Format 'yyyy-MM-dd'
$baseCount = $tables.Count
$histCount = (Query "SELECT COUNT(*) AS C FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME LIKE '%[_]History'").Rows[0].C

