W ""
W "## Conventions"
W ""
W "- **$baseCount base tables** are documented below. **$histCount ``*_History`` tables** are omitted: each is a"
W "  system-versioned temporal mirror of its base table with the same columns plus the period columns"
W "  ``SysStart`` / ``SysEnd``. Tables marked **(temporal)** below have such a history twin; query their"
W "  history with ``FOR SYSTEM_TIME ALL``."
W "- **PK** = primary-key column. **-> Table.Col** = foreign key to that column."
W "- ``Id`` columns are ``uniqueidentifier`` (GUID) unless noted. EF Core owns this schema (code-first migrations)."
