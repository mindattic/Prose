W "---"
W ""

function TypeStr($r) {
  $t = $r.DATA_TYPE
  $len = $r.CHARACTER_MAXIMUM_LENGTH
  if ($len -ne [DBNull]::Value -and $len -ne $null) {
    if ([int]$len -eq -1) { return "$t(max)" }
    return "$t($len)"
  }
  if ($t -in @('decimal','numeric') -and $r.NUMERIC_PRECISION -ne [DBNull]::Value) {
    return "$t($($r.NUMERIC_PRECISION),$($r.NUMERIC_SCALE))"
  }
  return $t
}

foreach ($g in $tables) {
  $name = $g.Name
  $tw = if ($temporalSet.ContainsKey($name)) { ' *(temporal -- has `' + $name + '_History`)*' } else { '' }
  $rc = if ($rcMap.ContainsKey($name)) { $rcMap[$name] } else { 0 }
  W "### $name"
  W ""
  W "~$rc rows.$tw"
  W ""
  W "| # | Column | Type | Null | Key |"
  W "|---|--------|------|------|-----|"
  foreach ($c in $g.Group) {
    $type = TypeStr $c
    $null = if ($c.IS_NULLABLE -eq 'YES') { 'yes' } else { 'no' }
    $key = ''
    if ($pkSet.ContainsKey("$name|$($c.COLUMN_NAME)")) { $key = 'PK' }
    if ($fkMap.ContainsKey("$name|$($c.COLUMN_NAME)")) {
      $fk = '-> ' + $fkMap["$name|$($c.COLUMN_NAME)"]
      $key = if ($key) { "$key, $fk" } else { $fk }
    }
    W "| $($c.ORDINAL_POSITION) | ``$($c.COLUMN_NAME)`` | $type | $null | $key |"
  }
  W ""
}

