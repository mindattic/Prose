  function findEl(selectors, doc) {
    doc = doc || document;
    if (typeof selectors === 'string') return doc.querySelector(selectors);
    for (var i = 0; i < selectors.length; i++) {
      var el = doc.querySelector(selectors[i]);
      if (el) return el;
    }
    return null;
  }

  // KDP's own button/link copy drifts across redesigns and we have no way to inspect the live
  // DOM from outside a browser — matching by visible text across a few plausible variants is
  // more resilient than guessing a CSS selector we can never verify.
  function findByText(tags, patterns) {
    var els = document.querySelectorAll(tags.join(','));
    for (var i = 0; i < els.length; i++) {
      var txt = (els[i].textContent || '').trim().toLowerCase();
      if (!txt) continue;
      for (var j = 0; j < patterns.length; j++) {
        if (txt.indexOf(patterns[j].toLowerCase()) !== -1) return els[i];
      }
    }
    return null;
  }

  function setVal(el, value) {
    var proto = el.tagName === 'TEXTAREA'
      ? window.HTMLTextAreaElement.prototype
      : window.HTMLInputElement.prototype;
    var desc = Object.getOwnPropertyDescriptor(proto, 'value');
    if (desc && desc.set) desc.set.call(el, value);
    else el.value = value;
    el.dispatchEvent(new Event('input',  { bubbles: true }));
    el.dispatchEvent(new Event('change', { bubbles: true }));
  }

  function waitForEl(selector, timeout) {
    return new Promise(function (resolve, reject) {
      var el = document.querySelector(selector);
      if (el) return resolve(el);
      var obs = new MutationObserver(function () {
        var found = document.querySelector(selector);
        if (found) { obs.disconnect(); resolve(found); }
      });
      obs.observe(document.body, { childList: true, subtree: true });
      setTimeout(function () { obs.disconnect(); reject(); }, timeout || 10000);
    });
  }

  function esc(s) {
    return String(s || '')
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }

  // Plain description.txt (blank-line-separated paragraphs) -> Amazon-allowed <b>/<br> markup.
  // First paragraph is the hook (bolded); the rest join with a blank line between them.
  function toDescriptionHtml(text) {
    var paras = String(text || '').split(/\n\s*\n/).map(function (p) {
      return esc(p.replace(/\s+/g, ' ').trim());
    }).filter(Boolean);
    if (paras.length === 0) return '';
    var hook = '<b>' + paras[0] + '</b>';
    return [hook].concat(paras.slice(1)).join('<br><br>');
  }

  function makeCopyBtn(getValue, tooltip) {
    var btn = document.createElement('button');
    btn.className = 'ss-copy-btn';
    btn.title = tooltip || 'Copy';
    btn.textContent = '⧉';
    btn.addEventListener('click', function (e) {
      e.stopPropagation();
      var text = typeof getValue === 'function' ? getValue() : getValue;
      navigator.clipboard.writeText(text).then(function () {
        btn.textContent = '✓';
        btn.classList.add('ss-copied');
        setTimeout(function () { btn.textContent = '⧉'; btn.classList.remove('ss-copied'); }, 1500);
      }).catch(function () {
        btn.textContent = '!';
        setTimeout(function () { btn.textContent = '⧉'; }, 1500);
      });
    });
    return btn;
  }

