  // RUNNER
  // ══════════════════════════════════════════════════════════════════════
  var runner = { steps: [], index: 0, busy: false };

  function execStep(index, sidebar) {
    if (index < 0 || index >= runner.steps.length) return;
    runner.index = index;
    runner.busy  = false;

    var step   = runner.steps[index];
    var action = step.action;

    renderStepList(sidebar);
    updateNavButtons(sidebar);

    if (action === 'pause') {
      if (step.watchFor) {
        waitForEl(step.watchFor, 30000).then(function () { setStepNote(sidebar, '⬆ Element appeared'); }).catch(function () {});
      }

    } else if (action === 'gotourl') {
      if (step.value) {
        setStepNote(sidebar, '⏳ Navigating…');
        window.location.href = step.value;
      } else {
        setStepNote(sidebar, '⚠ No direct link on file — find it on the bookshelf manually.');
      }

    } else if (action === 'copypath') {
      navigator.clipboard.writeText(step.value).catch(function () {});
      var fileEls = document.querySelectorAll('input[type="file"]');
      fileEls.forEach(function (fi) {
        fi.addEventListener('change', function onFilePicked() {
          fi.removeEventListener('change', onFilePicked);
          setStepNote(sidebar, '✓ File selected — click Next to continue');
        });
      });
      if (step.clickCandidates) {
        for (var i = 0; i < step.clickCandidates.length; i++) {
          var cand = step.clickCandidates[i];
          var el = findByText(cand.tags, cand.patterns);
          if (el) { el.click(); break; }
        }
      }
      if (step.watchFor) {
        waitForEl(step.watchFor, 60000).then(function () { setStepNote(sidebar, '✓ Upload complete — click Next'); }).catch(function () {});
      }

    } else if (action === 'fill') {
      var el = findEl(step.selectors);
      if (el) { setVal(el, step.value); setStepNote(sidebar, '✓ Filled'); }
      else    { setStepNote(sidebar, '⚠ Field not found — fill manually'); }

    } else if (action === 'richtext') {
      var ta = findEl(SEL.descArea);
      if (ta) {
        setVal(ta, step.value);
        setStepNote(sidebar, '✓ Injected');
      } else {
        var ce = findEl(SEL.descCE);
        if (ce) {
          ce.focus();
          ce.innerHTML = step.value;
          ['input', 'change', 'blur'].forEach(function (ev) { ce.dispatchEvent(new Event(ev, { bubbles: true })); });
          setStepNote(sidebar, '✓ Injected');
        } else {
          setStepNote(sidebar, '⚠ Editor not found — paste manually');
        }
      }

    } else if (action === 'click') {
      var btn = findEl(step.selectors);
      if (btn) { btn.click(); setStepNote(sidebar, '✓ Clicked'); }
      else     { setStepNote(sidebar, '⚠ Button not found — click manually'); }

    } else if (action === 'click-by-text') {
      var found = null;
      for (var j = 0; j < (step.clickCandidates || []).length; j++) {
        found = findByText(step.clickCandidates[j].tags, step.clickCandidates[j].patterns);
        if (found) break;
      }
      if (found) { found.click(); setStepNote(sidebar, '✓ Clicked'); }
      else       { setStepNote(sidebar, '⚠ Button not found — click manually'); }

    } else if (action === 'navigate') {
      var navBtn = findEl(step.selectors);
      if (navBtn) {
        runner.busy = true;
        updateNavButtons(sidebar);
        setStepNote(sidebar, '⏳ Waiting for page…');
        navBtn.click();
        waitForEl(step.waitFor, step.waitTimeout || 10000)
          .then(function () { runner.busy = false; setStepNote(sidebar, '✓ Page loaded'); updateNavButtons(sidebar); })
          .catch(function ()  { runner.busy = false; setStepNote(sidebar, '⚠ Timed out — continue manually'); updateNavButtons(sidebar); });
      } else {
        setStepNote(sidebar, '⚠ Button not found — click manually, then Next');
      }
    }
  }

  function goNext(sidebar) { if (!runner.busy && runner.index < runner.steps.length - 1) execStep(runner.index + 1, sidebar); }
  function goPrev(sidebar) { if (!runner.busy && runner.index > 0) execStep(runner.index - 1, sidebar); }

