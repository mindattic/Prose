  function renderStepList(sidebar) {
    var container = sidebar.querySelector('#ss-steps');
    if (!container) return;
    container.innerHTML = '';

    runner.steps.forEach(function (step, i) {
      var isDone   = i < runner.index;
      var isActive = i === runner.index;

      var row = document.createElement('div');
      row.className = 'ss-step' + (isDone ? ' ss-done' : isActive ? ' ss-active' : ' ss-pending');
      row.dataset.idx = i;

      var icon = isDone ? '✓' : isActive ? '▶' : String(i + 1);
      var detailTxt = step.message || step.detail || '';

      var iconEl = document.createElement('span');
      iconEl.className = 'ss-sicon';
      iconEl.textContent = icon;

      var body = document.createElement('div');
      body.className = 'ss-sbody';

      var labelRow = document.createElement('div');
      labelRow.style.cssText = 'display:flex; align-items:center; justify-content:space-between; gap:4px;';
      var labelEl = document.createElement('div');
      labelEl.className = 'ss-slabel';
      labelEl.textContent = step.label;
      labelRow.appendChild(labelEl);
      if (isActive && step.copyValue) labelRow.appendChild(makeCopyBtn(step.copyValue, step.copyTip || 'Copy'));
      body.appendChild(labelRow);

      if (isActive) {
        var detailEl = document.createElement('div');
        detailEl.className = 'ss-sdetail';
        detailEl.id = 'ss-active-detail';
        detailEl.textContent = detailTxt;
        body.appendChild(detailEl);
      }

      row.appendChild(iconEl);
      row.appendChild(body);
      row.addEventListener('click', function () { execStep(parseInt(row.dataset.idx, 10), sidebar); });
      container.appendChild(row);
    });

    var activeRow = container.querySelector('.ss-active');
    if (activeRow) activeRow.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
  }

  function setStepNote(sidebar, note) {
    var el = sidebar.querySelector('#ss-active-detail');
    if (el) el.textContent = note;
  }

