/**
 * generate_materials.js
 * Generates 200 material substrate entries as JSON files.
 * Avoids overwriting existing files in engine/data/substrates/.
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const OUTPUT_DIR = path.resolve(__dirname, "..", "engine", "data", "substrates");

function genId() {
  return crypto.randomBytes(16).toString("hex");
}

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")
    .slice(0, 80);
}

function writeMaterial(m) {
  const slug = slugify(m.name);
  const filePath = path.join(OUTPUT_DIR, slug + ".json");
  if (fs.existsSync(filePath)) {
    console.log(`SKIP (exists): ${slug}.json`);
    return false;
  }
  const entry = {
    id: genId(),
    name: m.name.slice(0, 60),
    brand_name: m.brand_name || "",
    product_name: m.product_name || "",
    type: "substrate",
    aliases: m.aliases || [],
    category: m.category,
    description: m.description,
    properties: m.properties || [],
    developers: m.developers || [],
    applications: m.applications || [],
    tier_availability: m.tier_availability || "",
    cost: m.cost || "",
    story_hooks: m.story_hooks || [],
    tags: ["substrate", "material", m.category, ...(m.tags || [])],
  };
  fs.writeFileSync(filePath, JSON.stringify(entry, null, 2) + "\n", "utf8");
  return true;
}

