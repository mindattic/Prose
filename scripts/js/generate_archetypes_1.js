// Check for existing files and write
if (!fs.existsSync(OUTPUT_DIR)) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

const existingFiles = new Set(fs.readdirSync(OUTPUT_DIR).map(f => f.toLowerCase()));
let written = 0;
let skipped = 0;

for (const archetype of archetypes) {
  const slug = slugify(archetype.name);
  const filename = slug + ".json";

  if (existingFiles.has(filename)) {
    console.log(`SKIP (exists): ${filename}`);
    skipped++;
    continue;
  }

  const record = {
    id: generateId(),
    name: archetype.name.slice(0, 60),
    type: "archetype",
    category: archetype.category,
    description: archetype.description,
    behavioral_signature: archetype.behavioral_signature,
    under_stress: archetype.under_stress,
    at_rest: archetype.at_rest,
    will_always: archetype.will_always,
    will_never: archetype.will_never,
    unless: archetype.unless,
    similar_to: archetype.similar_to,
    opposite_of: archetype.opposite_of,
    tags: archetype.tags
  };

  const filePath = path.join(OUTPUT_DIR, filename);
  fs.writeFileSync(filePath, JSON.stringify(record, null, 2) + "\n", "utf8");
  written++;
}

console.log(`\nDone: ${written} written, ${skipped} skipped`);
console.log(`Total files in directory: ${fs.readdirSync(OUTPUT_DIR).length}`);
